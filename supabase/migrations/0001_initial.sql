create extension if not exists pgcrypto;

create table public.mosque_settings (
  id smallint primary key default 1 check (id = 1),
  name text not null default 'Your local masjid',
  location text not null default 'Community prayer timetable',
  timezone text not null default 'Asia/Karachi',
  updated_at timestamptz not null default now()
);

create table public.prayer_times (
  id bigint generated by default as identity primary key,
  date date not null,
  prayer text not null check (prayer in ('Fajr', 'Dhuhr', 'Asr', 'Maghrib', 'Isha')),
  prayer_start time not null,
  jamaat time not null,
  updated_at timestamptz not null default now(),
  updated_by text not null,
  unique (date, prayer)
);

create table public.admin_members (
  id uuid primary key default gen_random_uuid(),
  email text not null unique check (email = lower(email)),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.push_subscriptions (
  endpoint text primary key,
  p256dh text not null,
  auth text not null,
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);

create table public.push_rate_limits (
  rate_key text primary key,
  window_started_at timestamptz not null default now(),
  attempts integer not null default 1 check (attempts > 0)
);

create table public.change_history (
  id bigint generated by default as identity primary key,
  date date not null,
  prayer text not null,
  old_jamaat time not null,
  new_jamaat time not null,
  changed_by text not null,
  changed_at timestamptz not null default now()
);

alter table public.mosque_settings enable row level security;
alter table public.prayer_times enable row level security;
alter table public.admin_members enable row level security;
alter table public.push_subscriptions enable row level security;
alter table public.push_rate_limits enable row level security;
alter table public.change_history enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admin_members
    where email = lower(coalesce(auth.jwt() ->> 'email', '')) and active = true
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

create policy "Public can read mosque settings"
on public.mosque_settings for select to anon, authenticated using (true);

create policy "Public can read prayer times"
on public.prayer_times for select to anon, authenticated using (true);

create policy "Members can see their own admin record"
on public.admin_members for select to authenticated
using (email = lower(coalesce(auth.jwt() ->> 'email', '')));

create policy "Admins can read change history"
on public.change_history for select to authenticated using (public.is_admin());

create or replace function public.register_push_subscription(
  p_endpoint text,
  p_p256dh text,
  p_auth text,
  p_rate_key text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_attempts integer;
begin
  insert into public.push_rate_limits (rate_key, window_started_at, attempts)
  values (p_rate_key, now(), 1)
  on conflict (rate_key) do update
  set
    window_started_at = case
      when push_rate_limits.window_started_at < now() - interval '1 day' then now()
      else push_rate_limits.window_started_at
    end,
    attempts = case
      when push_rate_limits.window_started_at < now() - interval '1 day' then 1
      else push_rate_limits.attempts + 1
    end
  returning attempts into v_attempts;

  if v_attempts > 10 then
    raise exception 'rate limit exceeded';
  end if;

  insert into public.push_subscriptions (
    endpoint, p256dh, auth, created_at, last_seen_at
  ) values (
    p_endpoint, p_p256dh, p_auth, now(), now()
  )
  on conflict (endpoint) do update
  set p256dh = excluded.p256dh,
      auth = excluded.auth,
      last_seen_at = now();
end;
$$;

create or replace function public.publish_prayer_schedule(
  p_date date,
  p_times jsonb,
  p_changed_by text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_item jsonb;
  v_prayer text;
  v_start time;
  v_jamaat time;
  v_old_jamaat time;
  v_changes jsonb := '[]'::jsonb;
begin
  if jsonb_typeof(p_times) <> 'array' or jsonb_array_length(p_times) <> 5 then
    raise exception 'all five prayer times are required';
  end if;

  if (
    select count(distinct item ->> 'prayer') <> 5
    from jsonb_array_elements(p_times) as item
    where item ->> 'prayer' in ('Fajr', 'Dhuhr', 'Asr', 'Maghrib', 'Isha')
  ) then
    raise exception 'each prayer must appear exactly once';
  end if;

  for v_item in select value from jsonb_array_elements(p_times)
  loop
    v_prayer := v_item ->> 'prayer';
    v_start := (v_item ->> 'prayer_start')::time;
    v_jamaat := (v_item ->> 'jamaat')::time;

    select jamaat into v_old_jamaat
    from public.prayer_times
    where date = p_date and prayer = v_prayer;

    if not found then
      v_old_jamaat := case v_prayer
        when 'Fajr' then '05:45'::time
        when 'Dhuhr' then '13:15'::time
        when 'Asr' then '16:00'::time
        when 'Maghrib' then '17:40'::time
        when 'Isha' then '19:30'::time
      end;
    end if;

    if v_old_jamaat is distinct from v_jamaat then
      insert into public.change_history (
        date, prayer, old_jamaat, new_jamaat, changed_by, changed_at
      ) values (
        p_date, v_prayer, v_old_jamaat, v_jamaat, p_changed_by, now()
      );
      v_changes := v_changes || jsonb_build_array(jsonb_build_object(
        'prayer', v_prayer,
        'oldJamaat', to_char(v_old_jamaat, 'HH24:MI'),
        'newJamaat', to_char(v_jamaat, 'HH24:MI')
      ));
    end if;

    insert into public.prayer_times (
      date, prayer, prayer_start, jamaat, updated_at, updated_by
    ) values (
      p_date, v_prayer, v_start, v_jamaat, now(), p_changed_by
    )
    on conflict (date, prayer) do update
    set prayer_start = excluded.prayer_start,
        jamaat = excluded.jamaat,
        updated_at = excluded.updated_at,
        updated_by = excluded.updated_by;
  end loop;

  update public.mosque_settings set updated_at = now() where id = 1;
  return v_changes;
end;
$$;

revoke all on function public.register_push_subscription(text, text, text, text) from public;
revoke all on function public.publish_prayer_schedule(date, jsonb, text) from public;
grant execute on function public.register_push_subscription(text, text, text, text) to service_role;
grant execute on function public.publish_prayer_schedule(date, jsonb, text) to service_role;

insert into public.mosque_settings (id) values (1) on conflict (id) do nothing;

grant select on public.mosque_settings, public.prayer_times to anon, authenticated;
grant select on public.admin_members, public.change_history to authenticated;
